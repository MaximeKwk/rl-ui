  const DICT = { en, fr };
  const LANGS = ['en', 'fr'];
  const norm = (lang) => (LANGS.includes(lang) ? lang : 'en');

  function fill(s, vars) {
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  }

  function t(lang, key, vars) {
    const d = DICT[norm(lang)];
    const s = d[key] != null ? d[key] : en[key] != null ? en[key] : key;
    return fill(s, vars);
  }

  // Pluriel : "clé" (singulier) / "clé.n" (pluriel). En français 0 et 1 sont au singulier.
  function tn(lang, key, n, vars) {
    const one = norm(lang) === 'fr' ? Math.abs(n) < 2 : Math.abs(n) === 1;
    return t(lang, one ? key : `${key}.n`, { n, ...(vars || {}) });
  }

